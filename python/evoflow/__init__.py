try:
    from . import _core
except ImportError as _core_error:
    _package_dir = _Path(__file__).resolve().parent
    _bundled = sorted(
        path.name
        for path in _package_dir.glob("_core.*")
        if path.suffix.lower() in (".pyd", ".so", ".dylib")
    )
    _current = "{} {}.{} ({}-bit, {})".format(
        _sys.implementation.name,
        _sys.version_info[0],
        _sys.version_info[1],
        8 * _struct.calcsize("P"),
        _sysconfig.get_platform(),
    )
    raise ImportError(
        "EvoFlow native module is unavailable for {}. Bundled binaries: {}. "
        "Use a matching CPython/ABI/platform build or run build-python.ps1 "
        "with that interpreter. Original loader error: {}".format(
            _current, ", ".join(_bundled) if _bundled else "none", _core_error
        )
    ) from _core_error
