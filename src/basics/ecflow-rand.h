	//   自原 basicfunc.h 恢复(新 basics 迁移遗漏);inline 于头,不重建 libbasics。
	//   注:新 rand01() = uniform_real[0,1) 半开(原为闭 [0,1]),故实际只会拒到 0;>=1 分支为语义保险。
